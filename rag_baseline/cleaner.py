"""
清洗：「这个语料里什么算脏、该怎么洗」只定义一次，两处消费：
  · 原项目 Eval/pipeline.py 拿它做体检（量库里还剩多少噪声）
  · clean_md() 拿它真删
共用一份定义，就不会出现「体检说干净了、清洗删的却是别的东西」。
内容对齐原项目 ingest.py 的 clean_md —— 同一个语料，同一套噪声。
"""
import re

# 每条 =（标签, 正则, 替换成什么）。替换成 "" 是纯删，替换成 r"\1" 是保留捕获组。
# **顺序有意义**：提示框那两条不能反，理由见下面。
CLEAN_RULES = [
    # \A 是字符串开头，不能写成 ^ —— ^ 配了 re.M 会匹配每一行，正文里的 --- 分隔线也会中招。
    # .*? 必须非贪婪：写成 .* 会从第一个 --- 一路吃到最后一个 ---，整篇文档就没了。
    ("frontmatter",     re.compile(r"\A---\n.*?\n---\n", re.S), ""),
    # 只能用 [ \t]，**不能**用 \s —— \s 会吃掉锚点后面的换行，把标题和下一段正文
    # 粘成一行，切块器的 \n\n 分隔符失效，整个章节层级就崩了（原项目踩过这个坑）。
    ("锚点 { #xxx }",    re.compile(r"[ \t]*\{[ \t]*#[^}]*\}[ \t]*"), ""),
    ("源码引用 {* *}",   re.compile(r"\{\*[^}]*\*\}"), ""),
    # 这两条**顺序不能反**：先用上一条把「/// tip | 提示」变成「【提示】」（"提示"两个字
    # 有语义，要留），再用这条删掉剩下的 /// 边界行。
    # 反了的话这条会先把「/// tip | 提示」整行删掉，"提示"跟着没了，上一条永远轮不到。
    ("提示框标签",       re.compile(r"^///\s*\w+\s*\|\s*(.+)$", re.M), r"【\1】"),
    ("提示框边界 ///",   re.compile(r"^///.*$", re.M), ""),
    # 必须以字母开头（防止误吃正文里的 x < y），必须以 > 闭合（同理）。
    ("HTML 标签",        re.compile(r"</?[a-zA-Z][a-zA-Z0-9]*(?:\s[^>]*)?>"), ""),
    # 保留方括号里的文字，只删 URL。
    ("markdown 链接",    re.compile(r"\[([^\]]+)\]\([^)]+\)"), r"\1"),
]

# 这一批先不洗的规则。注意：体检**照旧会量**它们，只是这一批不删 ——
# 「量出来还有多少」和「这一批洗不洗」是两件事。
# 改这里 → 语料指纹自动变 → 自动重建，不用手动改 REBUILD（见 vectorstore.corpus_signature）。
CLEAN_SKIP = {"markdown 链接"}

# 这些「看起来最脏」但**是信号本身**，清洗时必须原样留着。
# 单独列出来是为了防手滑：案例集里 must 那一列（UploadFile / Depends / response_model /
# allow_origins）**全都住在行内代码里**。洗掉它们，检索是干净了，答案彻底废了。
SIGNAL_PATTERNS = {
    "行内代码 `x`":     re.compile(r"`[^`]+`"),
    "代码块 ```":       re.compile(r"```"),
}


def is_corpus_noise_file(name):
    """语料仓库里的非文档文件：测试产物（_llm-test.md）、页面碎片（翻译横幅）。

    和原项目 ingest.py 同一套定义 —— 那边实测过：CORS 查询的第 4 名就是 _llm-test.md 的垃圾块。
    """
    return name.startswith("_") or name == "translation-banner.md"


def clean_md(text):
    """洗一篇文档的正文。规则在 CLEAN_RULES 里，一条一条按顺序过。

    **位置很关键：在切块之前。** CHUNK_SIZE 是**字符数**上限 —— 块里如果有 100 个字符
    是 mkdocs 语法，这块就只剩 400 字真内容，有效信息密度少 20%。先洗净再切，
    同样 500 字的块能装更多正文；切块器看到的 \\n\\n 也不再被 /// 行污染。

    三条军规（每条都对应一个真踩过的坑）：
      ① 宁可漏，不可错杀。漏了下次补一条规则；错杀的是真内容，而且**不报错**。
      ② 正则必须完整闭合。`[^}]*` 而不是 `.*`；`>` 必须出现，不能可选。
         写松了正则会从标记一路吃到行尾，把正文整段吞掉。
      ③ 只删标记，留正文。锚点删掉但那句标题留着；/// 边界删掉但框里的知识留着。
    """
    for label, rx, repl in CLEAN_RULES:
        if label in CLEAN_SKIP:
            continue
        text = rx.sub(repl, text)
    # 删完之后留下的连续空行（一条 /// 规则删掉一行，就留下两个换行）
    return re.sub(r"\n{3,}", "\n\n", text).strip()

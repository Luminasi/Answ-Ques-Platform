"""
⑦ 生成：资料 → 答案。
"""
def generate(llm, question, hits):
    """资料 → 答案。提示词里那几条要求，每一条都是踩出来的：

    原来只有一句「若资料中没有相关信息，请如实告知」。问题出在**资料只覆盖了一部分**
    的时候 —— 那句话没说这种算「没有」还是算「有」，模型就自由发挥，一半概率
    用「资料中没有给出完整的 X…」**开头**，然后再给内容。

    于是同一份资料、同一个问题，答案有了两种形状：先给内容 / 先认怂。
    实测（固定输入跑 3 遍）：裁判对「先认怂」这个形状是**稳定地判不过**的 ——
    不是它乱摇，是被形状触发的。而形状会摇，温度压不住（temp 0.0 照样先认怂）。

    所以这里把话说死：**先答，后免责，不许拿免责句开头。**
    顺带也让答案更像人话 —— 用户要的是答案，不是致歉。
    """
    context = "\n\n".join(doc.page_content for doc, _ in hits)
    prompt = (
        f"请根据以下资料回答问题。\n\n"
        f"资料：\n{context}\n\n"
        f"问题：{question}\n\n"
        "回答要求：\n"
        "1. 先直接回答，把资料里能支持这个问题的内容（步骤、代码、要点）完整写出来。\n"
        "2. 资料往往只覆盖问题的一部分，这很正常 —— **照样先答已有的那部分**，\n"
        "   确有余下没覆盖到的，放到**最后**再补一句说明。\n"
        "3. **不要用「资料中没有…」「资料里没有给出…」这类句子开头。**\n"
        "   只有资料**完全**答不了这个问题时，才直接说明不知道。\n"
        "4. 以上内容都必须出自资料，不要自己补充资料里没有的东西。"
    )
    return llm.invoke(prompt).content
